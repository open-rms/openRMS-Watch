//! One supervised decoder per (channel, shift):
//!
//!   source (SDR command | file) --s16le 8k--> [shift] --s32le--> FIFO --> mercury -x fifo
//!   mercury control port --"MONITOR ..." lines--> events --> DB writer
//!
//! Mercury runs as a separate process with a generated INI (PTT none, store
//! off), so nothing links GPL code and a personal mercury.ini is never read.

use crate::config::{Channel, Receiver};
use crate::db::{now_ms, Heard};
use crate::dsp::Shifter;
use anyhow::{bail, Context, Result};
use std::io::{BufRead, BufReader, Read, Write};
use std::net::TcpStream;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::mpsc::Sender;
use std::sync::Arc;
use std::time::{Duration, Instant};
use tracing::{info, warn};

pub enum Event {
    Frame(Heard),
    Coverage { channel_id: i64, start_ms: i64, end_ms: i64 },
}

pub struct Instance {
    pub name: String,
    pub channel: Channel,
    pub channel_id: i64,
    pub receiver: Receiver,
    pub shift_hz: f64,
    pub port: u16,
    pub dir: PathBuf,
    pub mercury: PathBuf,
    pub connect_only: bool,
}

const RATE: usize = 8000;
const CHUNK: usize = 160;
const COVERAGE_EVERY: Duration = Duration::from_secs(30);

/// Kill a child and its whole process group (sh -c pipelines).
pub(crate) struct Group(pub(crate) Child);
impl Drop for Group {
    fn drop(&mut self) {
        let pid = self.0.id() as i32;
        unsafe {
            libc::kill(-pid, libc::SIGTERM);
        }
        let deadline = Instant::now() + Duration::from_secs(3);
        while Instant::now() < deadline {
            if let Ok(Some(_)) = self.0.try_wait() {
                return;
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        unsafe {
            libc::kill(-pid, libc::SIGKILL);
        }
        let _ = self.0.wait();
    }
}

pub(crate) fn spawn_group(cmd: &mut Command) -> std::io::Result<Group> {
    unsafe {
        cmd.pre_exec(|| {
            // Die with the watcher even if it is SIGKILLed.
            libc::prctl(libc::PR_SET_PDEATHSIG, libc::SIGTERM);
            Ok(())
        });
    }
    cmd.process_group(0);
    cmd.spawn().map(Group)
}

pub(crate) fn mkfifo(path: &Path) -> Result<()> {
    let _ = std::fs::remove_file(path);
    let c = std::ffi::CString::new(path.as_os_str().as_encoded_bytes())?;
    if unsafe { libc::mkfifo(c.as_ptr(), 0o600) } != 0 {
        bail!("mkfifo {}: {}", path.display(), std::io::Error::last_os_error());
    }
    Ok(())
}

/// Open the FIFO for writing once Mercury has its read end open (ENXIO until then).
pub(crate) fn open_fifo_writer(path: &Path, stop: &AtomicBool) -> Result<std::fs::File> {
    use std::os::unix::fs::OpenOptionsExt;
    let deadline = Instant::now() + Duration::from_secs(30);
    loop {
        match std::fs::OpenOptions::new().write(true).custom_flags(libc::O_NONBLOCK).open(path) {
            Ok(f) => {
                // back to blocking writes: Mercury's backpressure paces us
                use std::os::fd::AsRawFd;
                let fd = f.as_raw_fd();
                unsafe {
                    let fl = libc::fcntl(fd, libc::F_GETFL);
                    libc::fcntl(fd, libc::F_SETFL, fl & !libc::O_NONBLOCK);
                }
                return Ok(f);
            }
            Err(e) if e.raw_os_error() == Some(libc::ENXIO) => {
                if stop.load(Ordering::Relaxed) || Instant::now() > deadline {
                    bail!("mercury never opened {}", path.display());
                }
                std::thread::sleep(Duration::from_millis(100));
            }
            Err(e) => return Err(e.into()),
        }
    }
}

impl Instance {
    /// Total audio correction for this decoder, Hz.
    pub fn total_shift_hz(&self) -> f64 {
        let tool_corrects = self.channel.command.as_deref().is_some_and(|c| c.contains("{ppm}"));
        let ppm = if tool_corrects { 0.0 } else { self.receiver.ppm * 1e-6 * self.channel.dial_hz as f64 };
        self.receiver.offset_hz + ppm + self.shift_hz
    }

    fn write_ini(&self, fifo: &Path) -> Result<PathBuf> {
        let ini = self.dir.join("mercury.ini");
        std::fs::write(
            &ini,
            format!(
                "; generated by openrms-watch: receive-only monitor\n\
                 [main]\nui_enabled = false\nsound_system = fifo\n\
                 input_device = {}\noutput_device = /dev/null\n\
                 arq_tcp_base_port = {}\nbroadcast_tcp_port = {}\n\
                 [ptt]\nmethod = none\n[store]\nenabled = false\n",
                fifo.display(),
                self.port,
                self.port + 2
            ),
        )?;
        Ok(ini)
    }

    fn source_command(&self) -> Option<String> {
        self.channel.command.as_ref().map(|c| {
            c.replace("{dial_hz}", &self.channel.dial_hz.to_string())
                .replace("{dial_khz}", &format!("{:.3}", self.channel.dial_hz as f64 / 1000.0))
                .replace("{ppm}", &format!("{}", self.receiver.ppm))
        })
    }

    /// Supervise forever (until `stop`), restarting with backoff.
    pub fn run(self, tx: Sender<Event>, stop: Arc<AtomicBool>) {
        let mut backoff = 2u64;
        while !stop.load(Ordering::Relaxed) {
            let started = Instant::now();
            match self.run_once(&tx, &stop) {
                Ok(true) => {
                    info!("[{}] source finished", self.name);
                    return;
                }
                Ok(false) => {}
                Err(e) => warn!("[{}] {e:#}", self.name),
            }
            if stop.load(Ordering::Relaxed) {
                break;
            }
            if started.elapsed() > Duration::from_secs(300) {
                backoff = 2;
            }
            info!("[{}] restarting in {backoff}s", self.name);
            for _ in 0..backoff * 10 {
                if stop.load(Ordering::Relaxed) {
                    return;
                }
                std::thread::sleep(Duration::from_millis(100));
            }
            backoff = (backoff * 2).min(60);
        }
    }

    /// Ok(true): a non-looping file source ended (don't restart).
    fn run_once(&self, tx: &Sender<Event>, stop: &Arc<AtomicBool>) -> Result<bool> {
        std::fs::create_dir_all(&self.dir)?;
        let fifo = self.dir.join("audio.fifo");
        mkfifo(&fifo)?;
        let ini = self.write_ini(&fifo)?;
        let log = std::fs::File::create(self.dir.join("mercury.log"))?;
        let _mercury = spawn_group(
            Command::new(&self.mercury)
                .arg("-C")
                .arg(&ini)
                .current_dir(&self.dir)
                .env("MERCURY_MONITOR_CONNECT_ONLY", if self.connect_only { "1" } else { "0" })
                .env("MERCURY_BIND_ADDR", "127.0.0.1")
                .stdin(Stdio::null())
                .stdout(log.try_clone()?)
                .stderr(log),
        )
        .with_context(|| format!("starting {}", self.mercury.display()))?;

        // Control connection: turn monitor on before feeding audio.
        let mut ctl = None;
        for _ in 0..150 {
            if let Ok(s) = TcpStream::connect(("127.0.0.1", self.port)) {
                ctl = Some(s);
                break;
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        let mut ctl = ctl.context("mercury control port never opened")?;
        ctl.write_all(b"MONITOR ON\r")?;
        ctl.set_read_timeout(Some(Duration::from_millis(500)))?;

        // Audio pump thread.
        let samples = Arc::new(AtomicU64::new(0));
        let audio_done = Arc::new(AtomicBool::new(false));
        let file_finished = Arc::new(AtomicBool::new(false));
        let local_stop = Arc::new(AtomicBool::new(false));
        let (src_child, reader): (Option<Group>, Box<dyn Read + Send>) = if let Some(cmd) = self.source_command() {
            let errlog = std::fs::File::create(self.dir.join("source.log"))?;
            let mut g = spawn_group(
                Command::new("sh")
                    .arg("-c")
                    .arg(&cmd)
                    .stdin(Stdio::null())
                    .stdout(Stdio::piped())
                    .stderr(errlog),
            )
            .with_context(|| format!("starting source: {cmd}"))?;
            let out = g.0.stdout.take().unwrap();
            info!("[{}] source: {cmd}", self.name);
            (Some(g), Box::new(out))
        } else {
            let path = self.channel.file.clone().unwrap();
            (None, Box::new(PacedFile::open(&path, self.channel.loop_file)?))
        };
        let pump = {
            let fifo = fifo.clone();
            let samples = samples.clone();
            let audio_done = audio_done.clone();
            let file_finished = file_finished.clone();
            let local_stop = local_stop.clone();
            let shift = self.total_shift_hz();
            let is_file = self.channel.file.is_some();
            let name = self.name.clone();
            std::thread::spawn(move || {
                let r = pump_audio(reader, &fifo, shift, &samples, &local_stop);
                match r {
                    Ok(()) if is_file => file_finished.store(true, Ordering::Relaxed),
                    Ok(()) => warn!("[{name}] source closed its output"),
                    Err(e) => warn!("[{name}] audio: {e:#}"),
                }
                audio_done.store(true, Ordering::Relaxed);
            })
        };

        // Read MONITOR lines; account coverage while audio flows.
        let mut rd = BufReader::new(ctl.try_clone()?);
        let mut buf = Vec::new();
        let mut last_cov = Instant::now();
        let mut cov_start = now_ms();
        let mut last_samples = 0u64;
        let mut stalled_since: Option<Instant> = None;
        let result = loop {
            if stop.load(Ordering::Relaxed) {
                break Ok(false);
            }
            if audio_done.load(Ordering::Relaxed) {
                // Let Mercury finish decoding the tail of a file.
                if file_finished.load(Ordering::Relaxed) {
                    drain_lines(&mut rd, &mut buf, Duration::from_secs(4), |l| self.emit(tx, l));
                    break Ok(true);
                }
                break Ok(false);
            }
            buf.clear();
            match rd.read_until(b'\r', &mut buf) {
                Ok(0) => break Err(anyhow::anyhow!("mercury closed the control port")),
                Ok(_) => {
                    let line = String::from_utf8_lossy(&buf);
                    self.emit(tx, &line);
                }
                Err(e) if matches!(e.kind(), std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut) => {}
                Err(e) => break Err(e.into()),
            }
            if last_cov.elapsed() >= COVERAGE_EVERY {
                let n = samples.load(Ordering::Relaxed);
                let got = n - last_samples;
                let expected = (last_cov.elapsed().as_secs_f64() * RATE as f64) as u64;
                last_samples = n;
                last_cov = Instant::now();
                let now = now_ms();
                if got * 2 >= expected {
                    // one coverage report per channel, not one per offset-search decoder
                    if self.shift_hz == self.channel.shifts_hz[0] {
                        let _ = tx.send(Event::Coverage { channel_id: self.channel_id, start_ms: cov_start, end_ms: now });
                    }
                    stalled_since = None;
                } else {
                    warn!("[{}] audio underrun: {got} of {expected} samples", self.name);
                    let since = *stalled_since.get_or_insert_with(Instant::now);
                    if since.elapsed() > Duration::from_secs(60) {
                        break Err(anyhow::anyhow!("audio stalled for over a minute"));
                    }
                }
                cov_start = now;
            }
        };
        local_stop.store(true, Ordering::Relaxed);
        drop(src_child); // kills the SDR pipeline, unblocking the pump's read
        drop(_mercury); // kills mercury, unblocking the pump's write
        let _ = pump.join();
        result
    }

    fn emit(&self, tx: &Sender<Event>, line: &str) {
        if let Some(frame) = crate::monitor::parse_line(line) {
            info!("[{}] {}", self.name, frame.raw);
            let _ = tx.send(Event::Frame(Heard {
                ts_ms: now_ms(),
                receiver_id: self.receiver.id.clone(),
                channel_id: self.channel_id,
                dial_hz: self.channel.dial_hz,
                shift_hz: self.total_shift_hz(),
                freq_source: "channel",
                frame,
            }));
        }
    }
}

fn drain_lines(rd: &mut BufReader<TcpStream>, buf: &mut Vec<u8>, dur: Duration, mut f: impl FnMut(&str)) {
    let end = Instant::now() + dur;
    while Instant::now() < end {
        buf.clear();
        match rd.read_until(b'\r', buf) {
            Ok(0) => return,
            Ok(_) => f(&String::from_utf8_lossy(buf)),
            Err(_) => {}
        }
    }
}

fn pump_audio(
    mut src: Box<dyn Read + Send>,
    fifo: &Path,
    shift_hz: f64,
    samples: &AtomicU64,
    stop: &AtomicBool,
) -> Result<()> {
    let mut out = open_fifo_writer(fifo, stop)?;
    let mut shifter = Shifter::new(shift_hz, RATE as f64);
    let mut inb = vec![0u8; CHUNK * 2];
    let mut pcm = vec![0i16; CHUNK];
    let mut outb = vec![0u8; CHUNK * 4];
    while !stop.load(Ordering::Relaxed) {
        // read exactly one chunk (or EOF)
        let mut got = 0;
        while got < inb.len() {
            match src.read(&mut inb[got..]) {
                Ok(0) => break,
                Ok(n) => got += n,
                Err(e) if e.kind() == std::io::ErrorKind::Interrupted => {}
                Err(e) => return Err(e.into()),
            }
        }
        if got == 0 {
            // flush a little silence so Mercury decodes a frame ending at EOF
            let zeros = vec![0u8; RATE * 4 * 3];
            let _ = out.write_all(&zeros);
            return Ok(());
        }
        let n = got / 2;
        for i in 0..n {
            pcm[i] = i16::from_le_bytes([inb[2 * i], inb[2 * i + 1]]);
        }
        if let Some(s) = shifter.as_mut() {
            s.process(&mut pcm[..n]);
        }
        for i in 0..n {
            outb[4 * i..4 * i + 4].copy_from_slice(&((pcm[i] as i32) << 16).to_le_bytes());
        }
        out.write_all(&outb[..n * 4]).context("writing to mercury")?;
        samples.fetch_add(n as u64, Ordering::Relaxed);
    }
    Ok(())
}

/// A raw s16le 8 kHz file read back at real time.
pub(crate) struct PacedFile {
    f: std::fs::File,
    path: PathBuf,
    looping: bool,
    t0: Instant,
    sent: u64,
    bytes_per_s: f64,
}

impl PacedFile {
    pub(crate) fn open(path: &Path, looping: bool) -> Result<PacedFile> {
        Self::open_rate(path, looping, (RATE * 2) as f64)
    }

    pub(crate) fn open_rate(path: &Path, looping: bool, bytes_per_s: f64) -> Result<PacedFile> {
        Ok(PacedFile {
            f: std::fs::File::open(path).with_context(|| format!("opening {}", path.display()))?,
            path: path.into(),
            looping,
            t0: Instant::now(),
            sent: 0,
            bytes_per_s,
        })
    }
}

impl Read for PacedFile {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let due = self.t0 + Duration::from_secs_f64(self.sent as f64 / self.bytes_per_s);
        if let Some(d) = due.checked_duration_since(Instant::now()) {
            std::thread::sleep(d);
        }
        let mut n = self.f.read(buf)?;
        if n == 0 && self.looping {
            self.f = std::fs::File::open(&self.path)?;
            n = self.f.read(buf)?;
        }
        self.sent += n as u64;
        Ok(n)
    }
}
